"""Streamlit front end for optarb. Reads snapshots; never places orders or asks for credentials.

Run locally with ``streamlit run app.py``.
"""

from __future__ import annotations

import io

import pandas as pd
import plotly.graph_objects as go
import streamlit as st

from optarb.arbitrage import ScanConfig, best_per_group, box_rates, scan
from optarb.forwards import fit_all_forwards
from optarb.models import ExerciseStyle, OptionsChain
from optarb.providers.synthetic import make_chain, sample_chain
from optarb.smile import smile
from optarb.snapshot import from_frame
from optarb.study import persistence, run, simulate_session, summarize

st.set_page_config(page_title="Option no-arbitrage screener", layout="wide")

SOURCES = {
    "Demo: synthetic index chain with planted violations": "demo",
    "Demo: clean synthetic equity chain (American)": "clean",
    "Upload a recorded snapshot (.parquet)": "upload",
}


@st.cache_data(show_spinner=False)
def _demo(kind: str) -> OptionsChain:
    if kind == "demo":
        return sample_chain()
    return make_chain(symbol="SYN", exercise_style=ExerciseStyle.AMERICAN)


@st.cache_data(show_spinner=False)
def _simulated(n: int, seed: int):
    return simulate_session(n_snapshots=n, seed=seed)


HOVER = "K %{customdata[0]:g}<br>IV %{y:.2f}<br>off fit %{customdata[1]:+.2f} vol pts<extra></extra>"


def _legs_text(o) -> str:
    parts = []
    for leg in o.legs:
        name = "stock" if leg.instrument == "STOCK" else f"{leg.instrument.lower()} {leg.strike:g}"
        parts.append(f"{leg.action.lower()} {leg.quantity} {name} at {leg.price:.2f}")
    return "; ".join(parts)


# ---------------------------------------------------------------------------
# sidebar

with st.sidebar:
    st.header("Data")
    source = SOURCES[st.radio("Snapshot", list(SOURCES), label_visibility="collapsed")]
    uploaded = None
    if source == "upload":
        uploaded = st.file_uploader("Snapshot written by `optarb record`", type=["parquet"])
    st.header("Costs")
    commission = st.number_input("Commission per contract ($)", 0.0, 5.0, 0.65, 0.05)
    borrow = st.number_input("Stock borrow fee (annual)", 0.0, 0.5, 0.0, 0.005, format="%.3f")
    min_edge = st.number_input("Minimum net edge per package ($)", 0.0, 100.0, 0.01, 0.5)
    max_spread = st.slider("Skip quotes wider than (% of mid)", 1, 100, 100)
    st.header("Rate")
    use_rate = st.checkbox("Compare against a reference funding rate", value=True)
    ref_rate = st.number_input("Reference rate (annual)", 0.0, 0.2, 0.045, 0.0025, format="%.4f") if use_rate else None

cfg = ScanConfig(
    commission_per_contract=commission,
    borrow_rate=borrow,
    min_net_edge=min_edge,
    reference_rate=ref_rate,
    max_spread_pct=float(max_spread),
)

if source == "upload":
    if uploaded is None:
        st.title("Option no-arbitrage screener")
        st.write("Upload a snapshot recorded with `optarb record`, or pick a demo snapshot in the sidebar.")
        st.stop()
    chain = from_frame(pd.read_parquet(io.BytesIO(uploaded.getvalue())))
else:
    chain = _demo(source)

# ---------------------------------------------------------------------------
# header

st.title("Option no-arbitrage screener")
c1, c2, c3, c4 = st.columns(4)
c1.metric("Underlying", chain.symbol, f"{chain.underlying.bid:.2f} / {chain.underlying.ask:.2f}", delta_color="off")
c2.metric("Snapshot (UTC)", f"{chain.asof:%Y-%m-%d %H:%M}")
c3.metric("Exercise style", chain.exercise_style.value.title())
c4.metric("Quotes", f"{len(chain.quotes):,}")

if chain.source == "synthetic":
    st.info(
        "Synthetic data. This chain was generated by a model and, in the first demo, has violations planted on "
        "purpose so the checks have something to find. It says nothing about real markets."
    )
st.caption("Read-only research tool. It never connects to an account or places an order.")

found = scan(chain, cfg)
grouped = best_per_group(found)

tab_viol, tab_fwd, tab_smile, tab_study, tab_method = st.tabs(
    ["Violations", "Forwards and box rates", "Smile", "Study", "Method"]
)

with tab_viol:
    hard = [o for o in grouped if o.kind.value == "model_free"]
    rel = [o for o in grouped if o.kind.value == "rate_relative"]
    m1, m2, m3 = st.columns(3)
    m1.metric("Model-free violations", len(hard), help="best package per check and expiry")
    m2.metric("Rate-relative flags", len(rel))
    m3.metric("Packages in total", len(found))
    show_all = st.toggle("Show every package, not just the best per check and expiry")
    rows = found if show_all else grouped
    if not rows:
        st.success("No violations after costs at these settings.")
    else:
        table = pd.DataFrame(
            [
                {
                    "check": o.check,
                    "kind": o.kind.value,
                    "expiry": o.expiration,
                    "net $": o.net_edge,
                    "gross $": o.gross_edge,
                    "costs $": o.costs,
                    "trade": _legs_text(o),
                    "note": "; ".join(o.notes),
                }
                for o in rows
            ]
        )
        money = {c: st.column_config.NumberColumn(format="%.2f") for c in ("net $", "gross $", "costs $")}
        st.dataframe(table, hide_index=True, use_container_width=True, column_config=money)
        st.caption("Edges are dollars per package at executable bid/ask, with the 100-share multiplier.")

with tab_fwd:
    fits = fit_all_forwards(chain)
    if fits:
        st.subheader("Implied forward and discount factor")
        st.dataframe(
            pd.DataFrame(
                [
                    {
                        "expiry": e,
                        "years": f.T,
                        "discount factor": f.discount_factor,
                        "forward": f.forward,
                        "implied rate": f.implied_rate,
                        "implied carry (r - q)": f.implied_carry(chain.underlying.mid),
                        "strikes used": f.n_strikes,
                    }
                    for e, f in fits.items()
                ]
            ),
            hide_index=True,
            use_container_width=True,
        )
        if chain.exercise_style is ExerciseStyle.AMERICAN:
            st.warning("American options: early exercise bends put-call parity, so these fits are approximate.")
    else:
        st.write("Not enough two-sided strikes to fit a forward.")
    rates = box_rates(chain, cfg)
    if rates:
        st.subheader("Box-implied rates after commissions")
        st.dataframe(
            pd.DataFrame(
                [
                    {
                        "expiry": r.expiration,
                        "years": r.T,
                        "best lending rate": r.best_lend_rate,
                        "best borrowing rate": r.best_borrow_rate,
                    }
                    for r in rates
                ]
            ),
            hide_index=True,
            use_container_width=True,
        )

with tab_smile:
    exps = chain.expirations
    exp = st.selectbox("Expiry", exps, index=min(1, len(exps) - 1))
    pts = smile(chain, exp)
    if not pts:
        st.write("Not enough out-of-the-money quotes to fit a smile for this expiry.")
    else:
        df = pd.DataFrame(
            [
                {
                    "k": p.log_moneyness,
                    "strike": p.strike,
                    "right": p.right.value,
                    "iv": p.iv,
                    "fit": p.fitted_iv,
                    "resid": p.residual_vol_points,
                }
                for p in pts
            ]
        ).sort_values("k")
        fig = go.Figure()
        for right, name in (("P", "puts"), ("C", "calls")):
            d = df[df["right"] == right]
            fig.add_scatter(
                x=d["k"],
                y=100 * d["iv"],
                mode="markers",
                name=f"OTM {name}",
                customdata=d[["strike", "resid"]],
                hovertemplate=HOVER,
            )
        fig.add_scatter(x=df["k"], y=100 * df["fit"], mode="lines", name="quadratic fit")
        fig.update_layout(
            xaxis_title="log moneyness ln(K / F)",
            yaxis_title="implied vol (%)",
            height=420,
            margin=dict(l=10, r=10, t=10, b=10),
        )
        st.plotly_chart(fig, use_container_width=True)
        st.caption("Relative value, not arbitrage: a quote can sit off the fitted smile for good reasons.")

with tab_study:
    st.write(
        "The research question: how often do these bounds break at executable prices, by how much after costs, "
        "and for how long? Real answers need chains recorded over time with `optarb record`; this tab runs the "
        "same pipeline on a synthetic session so you can see what it measures."
    )
    n = st.slider("Snapshots (10 minutes apart)", 10, 60, 30)
    result = run(_simulated(n, 11), cfg)
    summary = summarize(result)
    st.info("Synthetic session with planted violations. The numbers describe the simulation only.")
    if summary.empty:
        st.write("No violations in this session at these settings.")
    else:
        st.dataframe(summary, hide_index=True, use_container_width=True)
        eps = persistence(result)
        fig = go.Figure()
        for check, g in eps.groupby("check"):
            fig.add_scatter(
                x=g["start"],
                y=g["max_net_edge"],
                mode="markers",
                name=check,
                marker=dict(size=6 + 4 * g["snapshots"]),
                hovertemplate="%{x}<br>$%{y:.2f}<extra></extra>",
            )
        fig.update_layout(
            xaxis_title="episode start",
            yaxis_title="best net edge ($ per package)",
            height=380,
            margin=dict(l=10, r=10, t=10, b=10),
        )
        st.plotly_chart(fig, use_container_width=True)
        st.caption("Marker size grows with how many consecutive snapshots the episode lasted.")

with tab_method:
    st.markdown(
        r"""
Every check buys at the ask and sells at the bid. Commissions, per-share costs and stock borrow are then
subtracted. Prices are per share; edges are reported per package with the 100-share multiplier.

| Check | Bound | Applies to |
|---|---|---|
| Strike monotonicity | $C(K_1) \ge C(K_2)$, $P(K_1) \le P(K_2)$ for $K_1 < K_2$ | all |
| Vertical width | $C(K_1) - C(K_2) \le K_2 - K_1$ | all |
| Butterfly convexity | $(K_3-K_1)V(K_2) \le (K_3-K_2)V(K_1) + (K_2-K_1)V(K_3)$ | all, any spacing |
| Box bounds | $0 \le \text{box} \le K_2 - K_1$ | European |
| Parity band | $S - D - K \le C - P \le S - K e^{-rT}$ | American |
| Calendar | $V(K, T_2) \ge V(K, T_1)$ for $T_2 > T_1$ | American |
| Box vs funding | box rate against a reference rate | European, rate-relative |

The implied forward and discount factor per expiry come from a weighted least-squares fit of
$C - P = DF \cdot F - DF \cdot K$, with strikes far off the line dropped. The smile tab uses those
to compute Black-76 implied vols, so no rate or dividend has to be guessed.

What a flag does not tell you: whether the quotes were live at the same instant, whether size was
available, or whether you would have been filled. That is what the study is for.
"""
    )
